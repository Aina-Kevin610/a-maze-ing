class Pattern:
    _patterns = patterns
    def __init__(self, text: str, spacing: int = 1):
        self.text = text
        self.spacing = spacing

    def create(self) -> list[list[list[int]]]:
        return [self._patterns[char] for char in self.text if char in self._patterns]

    def create_merged(self) -> list[list[int]]:
        glyphs = self.create()
        if not glyphs:
            return []
        sep = [0] * self.spacing
        result = []
        for row in range(len(glyphs[0])):
            line = []
            for i, glyph in enumerate(glyphs):
                line += glyph[row]
                if i < len(glyphs) - 1:
                    line += sep
            result.append(line)
        return result
    

